const TRAILING_DECORATION = /[\d\s!@#$%^&*()_+=.,;:?-]+$/;

export function isCommonPassword(candidate: string): boolean {
  const lower = candidate
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '');
  if (COMMON_PASSWORDS.has(lower)) return true;
  const stripped = lower.replace(TRAILING_DECORATION, '');
  if (stripped.length > 0 && COMMON_PASSWORDS.has(stripped)) return true;
  // Répétition d'un motif court (« abcabcabcabc », « 12121212... »).
  return /^(.{1,3})\1+$/.test(lower);
}
